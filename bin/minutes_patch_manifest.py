"""Render and enforce the list of files that differ from Signal RingRTC."""

from __future__ import annotations

import argparse
import fnmatch
import json
import subprocess
from pathlib import Path
from typing import Iterable


ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = Path("config/minutes_fork_patch_manifest.json")
DOCUMENT_PATH = Path("docs/MINUTES-PATCHES.md")


def load_manifest(root: Path) -> dict:
    return json.loads((root / MANIFEST_PATH).read_text(encoding="utf-8"))


def render_table(headers: tuple[str, str], rows: list[tuple[str, str]]) -> list[str]:
    widths = [
        max(len(headers[index]), *(len(row[index]) for row in rows))
        for index in range(2)
    ]

    def row(values: tuple[str, str]) -> str:
        return "| " + " | ".join(
            value.ljust(widths[index]) for index, value in enumerate(values)
        ) + " |"

    return [
        row(headers),
        row(("-" * widths[0], "-" * widths[1])),
        *(row(values) for values in rows),
    ]


def render(manifest: dict) -> str:
    lines = [
        "# Minutes RingRTC — upstream patch manifest",
        "",
        "<!-- Generated by bin/minutes_patch_manifest.py; edit the JSON manifest. -->",
        "",
        f"- Upstream: `{manifest['upstreamRepository']}`",
        f"- Baseline: `{manifest['upstreamTag']}`",
        "- Source of truth: `config/minutes_fork_patch_manifest.json`",
        "",
        "## Modified or removed upstream files",
        "",
    ]
    patch_rows: list[tuple[str, str]] = []
    for patch in manifest["upstreamPatches"]:
        purpose = str(patch["purpose"]).replace("|", "\\|")
        patch_rows.append((f"`{patch['path']}`", purpose))
    lines.extend(render_table(("Path", "Minutes delta"), patch_rows))
    lines.extend(
        [
            "",
            "## Fork-owned paths",
            "",
            "These patterns are kept beside upstream code and should not conflict with a sync.",
            "",
        ]
    )
    owned_rows: list[tuple[str, str]] = []
    for owned in manifest["forkOwnedPaths"]:
        purpose = str(owned["purpose"]).replace("|", "\\|")
        owned_rows.append((f"`{owned['pattern']}`", purpose))
    lines.extend(render_table(("Pattern", "Purpose"), owned_rows))
    lines.extend(
        [
            "",
            "## Required sync review",
            "",
            "1. Resolve merge conflicts without discarding upstream behavior.",
            "2. Keep native tap logic in fork-owned modules; upstream files contain glue only.",
            "3. Run `python3 bin/minutes_patch_manifest.py check --include-working-tree`.",
            "4. Run the focused Rust, Node distribution, and manifest tests.",
            "5. Record user-visible fork changes in `MINUTES-CHANGELOG.md`.",
            "",
        ]
    )
    return "\n".join(lines)


def parse_diff_names(output: str) -> set[str]:
    result: set[str] = set()
    for line in output.splitlines():
        fields = line.split("\t")
        if not fields:
            continue
        status = fields[0]
        if status.startswith(("R", "C")) and len(fields) >= 3:
            result.update(fields[1:3])
        elif len(fields) >= 2:
            result.add(fields[1])
    return result


def untracked_paths(output: str) -> set[str]:
    return {
        line[3:]
        for line in output.splitlines()
        if line.startswith("?? ") and len(line) > 3
    }


def classify_paths(manifest: dict, paths: Iterable[str]) -> tuple[set[str], set[str]]:
    changed = set(paths)
    upstream_paths = {entry["path"] for entry in manifest["upstreamPatches"]}
    owned_patterns = [entry["pattern"] for entry in manifest["forkOwnedPaths"]]
    unknown = {
        path
        for path in changed
        if path not in upstream_paths and not any(
            fnmatch.fnmatchcase(path, pattern) for pattern in owned_patterns
        )
    }
    stale = upstream_paths - changed
    return unknown, stale


def git_output(root: Path, args: list[str]) -> str:
    return subprocess.run(
        ["git", *args],
        cwd=root,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    ).stdout


def check(root: Path, include_working_tree: bool) -> None:
    manifest = load_manifest(root)
    expected_document = render(manifest)
    actual_document = (root / DOCUMENT_PATH).read_text(encoding="utf-8")
    if actual_document != expected_document:
        raise ValueError(
            "docs/MINUTES-PATCHES.md is stale; run "
            "python bin/minutes_patch_manifest.py render"
        )

    baseline = manifest["upstreamTag"]
    paths = parse_diff_names(
        git_output(root, ["diff", "--name-status", baseline, "HEAD"])
    )
    if include_working_tree:
        paths.update(
            parse_diff_names(git_output(root, ["diff", "--name-status", "HEAD"]))
        )
        paths.update(untracked_paths(git_output(root, ["status", "--porcelain"])))
    unknown, stale = classify_paths(manifest, paths)
    if unknown:
        raise ValueError("Unclassified fork paths: " + ", ".join(sorted(unknown)))
    if stale:
        raise ValueError(
            "Stale upstream patch entries (remove or reclassify): "
            ", ".join(sorted(stale))
        )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("render")
    check_parser = subparsers.add_parser("check")
    check_parser.add_argument("--include-working-tree", action="store_true")
    args = parser.parse_args()

    if args.command == "render":
        (args.root / DOCUMENT_PATH).write_text(
            render(load_manifest(args.root)), encoding="utf-8"
        )
    else:
        check(args.root, args.include_working_tree)


if __name__ == "__main__":
    main()
